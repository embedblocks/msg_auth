def derive(key: bytes, purpose: bytes) -> bytes:
    return hkdf_sha256(SALT, key, purpose, 32)


def envelope(dk: bytes, sender: int, receiver: int, epoch: int, counter: int, msg: bytes) -> bytes:
    hdr = struct.pack(">BBBBII", 1, 1, sender, receiver, epoch, counter)
    tag = hmac.new(dk, hdr + msg, hashlib.sha256).digest()[:16]
    return hdr + msg + tag


def c_array(name: str, data: bytes) -> str:
    if not data:
        return f"static const uint8_t {name}[1] = {{ 0 }};   /* empty */\n"
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 12]) for i in range(0, len(data), 12)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


